import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const defaultSource = resolve(scriptRoot, 'docs/community-gateway-disclosure.md');
const defaultOutput = resolve(scriptRoot, 'js/community-terms.generated.mjs');

export function normalizeTermsMarkdown(value) {
  return String(value).replaceAll('\r\n', '\n').replaceAll('\r', '\n').replace(/\n+$/, '');
}

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function inlineMarkup(value) {
  let text = escapeHtml(value);
  text = text.replace(/\[([^\]]+)\]\((https:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
  text = text.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  text = text.replace(/(?<!\*)\*([^*]+)\*(?!\*)/g, '<em>$1</em>');
  text = text.replace(/`([^`]+)`/g, '<code>$1</code>');
  return text;
}

function renderMarkdown(markdown) {
  const lines = normalizeTermsMarkdown(markdown).split('\n');
  const html = [];
  let paragraph = [];
  let listType = null;

  const closeParagraph = () => {
    if (paragraph.length) html.push(`<p>${inlineMarkup(paragraph.join(' '))}</p>`);
    paragraph = [];
  };
  const closeList = () => {
    if (listType) html.push(`</${listType}>`);
    listType = null;
  };

  for (const line of lines) {
    if (!line.trim()) {
      closeParagraph();
      closeList();
      continue;
    }
    const heading = /^(#{1,6})\s+(.+)$/.exec(line);
    if (heading) {
      closeParagraph();
      closeList();
      const level = heading[1].length;
      html.push(`<h${level}>${inlineMarkup(heading[2])}</h${level}>`);
      continue;
    }
    if (/^---+$/.test(line.trim())) {
      closeParagraph();
      closeList();
      html.push('<hr>');
      continue;
    }
    const unordered = /^-\s+(.+)$/.exec(line);
    const ordered = /^\d+\.\s+(.+)$/.exec(line);
    if (unordered || ordered) {
      closeParagraph();
      const nextType = unordered ? 'ul' : 'ol';
      if (listType !== nextType) {
        closeList();
        listType = nextType;
        html.push(`<${listType}>`);
      }
      html.push(`<li>${inlineMarkup((unordered || ordered)[1])}</li>`);
      continue;
    }
    const quote = /^>\s?(.*)$/.exec(line);
    if (quote) {
      closeParagraph();
      closeList();
      html.push(`<blockquote><p>${inlineMarkup(quote[1])}</p></blockquote>`);
      continue;
    }
    closeList();
    paragraph.push(line.trim().replace(/\s{2}$/, ''));
  }
  closeParagraph();
  closeList();
  return html.join('\n');
}

function requiredMatch(markdown, pattern, label) {
  const match = pattern.exec(markdown);
  if (!match) throw new Error(`Community disclosure is missing ${label}.`);
  return match[1].trim();
}

export function buildCommunityTermsArtifact(markdown) {
  const normalized = normalizeTermsMarkdown(markdown);
  const version = requiredMatch(normalized, /^\*\*Version:\*\*\s*(.+?)\s{0,2}$/m, 'a version');
  const effectiveDate = requiredMatch(normalized, /^\*\*Effective date:\*\*\s*(.+?)\s{0,2}$/m, 'an effective date');
  const acceptanceSection = normalized.split(/^## Acceptance Presented in the Gateway\s*$/m)[1];
  if (!acceptanceSection) throw new Error('Community disclosure is missing its acceptance statement.');
  const acceptanceText = requiredMatch(acceptanceSection, /^>\s+(.+)$/m, 'an acceptance statement');
  return {
    version,
    effectiveDate,
    documentSha256: createHash('sha256').update(normalized, 'utf8').digest('hex'),
    html: renderMarkdown(normalized),
    acceptanceText
  };
}

function moduleSource(artifact) {
  return `// Generated by scripts/generate-community-terms.mjs. Do not edit.\nexport const COMMUNITY_TERMS = Object.freeze(${JSON.stringify(artifact, null, 2)});\n`;
}

export async function generateCommunityTerms({ sourcePath = defaultSource, outputPath = defaultOutput, check = false } = {}) {
  const markdown = await readFile(sourcePath, 'utf8');
  const artifact = buildCommunityTermsArtifact(markdown);
  const expected = moduleSource(artifact);
  let current = false;
  try {
    current = (await readFile(outputPath, 'utf8')) === expected;
  } catch {
    current = false;
  }
  if (!check && !current) {
    await writeFile(outputPath, expected, 'utf8');
    current = true;
  }
  return { current, artifact };
}

async function main() {
  const check = process.argv.includes('--check');
  const result = await generateCommunityTerms({ check });
  if (check && !result.current) {
    process.stderr.write('Generated community terms are out of date. Run npm run generate:community-terms.\n');
    process.exitCode = 1;
    return;
  }
  process.stdout.write(`${check ? 'Verified' : 'Generated'} community terms ${result.artifact.version} (${result.artifact.documentSha256}).\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error) => {
    process.stderr.write(`Community terms generation failed: ${error.message}\n`);
    process.exitCode = 1;
  });
}
